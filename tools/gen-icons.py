"""Generates the extension's UI icons from the amicons "round-thin" set.

Writes:
  shared/icons.js      path data + helpers for icons in the sidebar and settings pages
  sidebar/icons.css    data-URL icons for CSS masks (also used by the settings page)
  content/probe.js     the toast's icons, between the "icons:start" and "icons:end" markers

Usage: python3 -I tools/gen-icons.py [path to amicons/round-thin]
"""
import json
import pathlib
import re
import sys
import urllib.parse

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '../amicons/round-thin')
ROOT = pathlib.Path(__file__).resolve().parent.parent

# Our name -> file name in the round-thin set.
ICONS = {
    'search': 'magnifying-glass',
    'options': 'sliders',
    'list': 'list',
    'grid': 'grid-2x2',
    'settings': 'gear',
    'warning': 'exclamation-triangle',
    'close': 'x',
    'more': 'dots-three-horizontal',
    'back': 'arrow-left',
    'delete': 'bin',
    'chevron': 'chevron-small-down',
    'up': 'chevron-small-up',
    'down': 'chevron-small-down',
    'grip': 'grip-vertical',
    'check': 'check',
    'progress': 'arrows-rotate-cw-horizontal',
    'image': 'image',
    'hash': 'hash',
    'plus': 'plus',
    # Settings page
    'globe': 'globe',
    'ok-circle': 'check-circle',
    'alert-circle': 'exclamation-circle',
    'history': 'history',
    'archive': 'archive',
    'export': 'arrow-to-bracket-down',
    'import': 'arrow-from-bracket-up',
    'storage': 'database',
}
CSS_MASKS = ['image', 'close', 'chevron']
TOAST = {'ok': 'check', 'warn': 'warning', 'progress': 'progress'}


def path_of(file):
    svg = (SRC / f'{file}.svg').read_text()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    assert len(paths) == 1 and 'viewBox="0 0 24 24"' in svg, f'{file}: expected one path on a 24x24 grid'
    return paths[0]


paths = {name: path_of(file) for name, file in ICONS.items()}

js = f'''// Generated by tools/gen-icons.py from the amicons "round-thin" set. Do not edit.
export const ICON_PATHS = {json.dumps(paths, indent=2)};

const SVG_NS = 'http://www.w3.org/2000/svg';

function fill(svg, name) {{
  const d = ICON_PATHS[name];
  if (!d) throw new Error(`Unknown icon: ${{name}}`);
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  const path = svg.ownerDocument.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', d);
  svg.replaceChildren(path);
  return svg;
}}

/** Creates an icon element: <svg class="icon {{className}}"> with the named path. */
export function createIcon(name, className = '') {{
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('class', `icon ${{className}}`.trim());
  return fill(svg, name);
}}

/** Fills every <svg data-icon="name"> under root, including inside <template>s. */
export function hydrateIcons(root = document) {{
  for (const svg of root.querySelectorAll('svg[data-icon]')) fill(svg, svg.dataset.icon);
  for (const tpl of root.querySelectorAll('template')) hydrateIcons(tpl.content);
}}
'''
(ROOT / 'shared/icons.js').write_text(js)


def data_url(d):
    svg = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'><path d='{d}'/></svg>"
    return 'url("data:image/svg+xml,' + urllib.parse.quote(svg, safe="/:=' ") + '")'


css = ['/* Generated by tools/gen-icons.py from the amicons "round-thin" set. Do not edit. */', ':root {']
css += [f'  --icon-{name}: {data_url(paths[name])};' for name in CSS_MASKS]
css += ['}', '']
(ROOT / 'sidebar/icons.css').write_text('\n'.join(css))

probe = ROOT / 'content/probe.js'
text = probe.read_text()
block = '\n'.join(f'    {k}: {json.dumps(paths[v])},' for k, v in TOAST.items())
new, n = re.subn(r'(/\* icons:start \*/).*?(\n[ \t]*/\* icons:end \*/)', lambda m: m.group(1) + '\n' + block + m.group(2), text, flags=re.S)
assert n == 1, 'icons:start/icons:end markers not found in content/probe.js'
probe.write_text(new)
print(f'{len(paths)} icons written')
