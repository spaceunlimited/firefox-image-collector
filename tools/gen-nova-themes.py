"""Generates shared/nova-themes.js from the manifests of Mozilla's Nova themes.

theme.getCurrent() only returns a theme's light colors. For Mozilla's own Nova themes we ship
their dark_theme colors, keyed by a fingerprint of the light colors, so the sidebar can match
Firefox when it shows the dark variant.

Usage: python3 -I tools/gen-nova-themes.py <dir with nova-*.json manifests> > shared/nova-themes.js
"""
import json
import pathlib
import sys

# Theme keys the extension uses (see THEME_MAP in shared/theme.js).
USED = [
    'sidebar', 'toolbar', 'frame', 'sidebar_text', 'toolbar_text', 'bookmark_text', 'tab_text',
    'tab_background_text', 'sidebar_border', 'toolbar_bottom_separator', 'popup_border', 'toolbar_field',
    'toolbar_field_text', 'toolbar_field_border', 'toolbar_field_border_focus', 'focus_outline', 'tab_line',
    'icons_attention', 'button_background_hover', 'button_background_active', 'sidebar_highlight',
    'popup_highlight', 'sidebar_highlight_text', 'popup_highlight_text', 'popup', 'popup_text', 'icons',
]
FINGERPRINT_KEYS = ['frame', 'sidebar', 'toolbar_field', 'tab_line']


def css(v):
    if isinstance(v, list):
        return ('rgba(' if len(v) == 4 else 'rgb(') + ', '.join(str(x) for x in v) + ')'
    return str(v).strip()


def fingerprint(colors):
    return '|'.join(css(colors.get(k, '')) for k in FINGERPRINT_KEYS)


rows = []
for path in sorted(pathlib.Path(sys.argv[1]).glob('*.json')):
    m = json.loads(path.read_text())
    if 'dark_theme' not in m:
        continue
    dark = {k: css(v) for k, v in m['dark_theme']['colors'].items() if k in USED}
    rows.append((m['browser_specific_settings']['gecko']['id'], m['name'], m['version'], fingerprint(m['theme']['colors']), dark))

prints = [r[3] for r in rows]
assert len(prints) == len(set(prints)), 'fingerprints are not unique'

out = [
    '// Generated by tools/gen-nova-themes.py from Mozilla\'s Nova themes on addons.mozilla.org. Do not edit.',
    '// Maps a fingerprint of a theme\'s light colors to its dark_theme colors.',
    f"export const FINGERPRINT_KEYS = {json.dumps(FINGERPRINT_KEYS)};",
    'export const NOVA_DARK = {',
]
for gid, name, version, fp, dark in rows:
    out.append(f'  // {name} ({gid} {version})')
    out.append(f'  {json.dumps(fp)}: {json.dumps(dark, separators=(", ", ": "))},')
out.append('};')
print('\n'.join(out))
